export function searchInstitutions(countryCode, query = '', accountType = 'bank') {
  const q = String(query || '').trim().toLocaleLowerCase();
  // E-wallet accounts list e-wallets; every other type lists banks plus card issuers and buy-now-pay-later lenders.
  const allowedKinds = accountType === 'e_wallet' ? ['ewallet'] : ['bank', 'lender'];
  return INSTITUTIONS
    .filter(item => item.country === countryCode && allowedKinds.includes(item.kind))
    .filter(item => !q || [item.name, ...item.aliases].some(value => value.toLocaleLowerCase().includes(q)))
    .sort((a, b) => a.name.localeCompare(b.name));
}


/** Logo for a curated institution, matched by its name or a known alias (e.g. "BDO", "PayMaya"); '' if none. */
export function institutionLogoUrl(name, options = {}) {
  const text = String(name || '').trim();
  if (!text) return '';
  const lower = text.toLowerCase();
  const inst = INSTITUTIONS.find(i => i.name.toLowerCase() === lower || i.aliases.some(a => a.toLowerCase() === lower));
  const candidates = [text, ...(inst ? [inst.name, ...inst.aliases] : [])];
  for (const c of candidates) { const url = getInstitutionFaviconUrl(c, options); if (url) return url; }
  return '';
}
